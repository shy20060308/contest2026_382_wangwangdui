const fs = require('fs')
const path = require('path')

const root = path.resolve(__dirname, '..')
const manifestFile = path.join(root, 'src', 'manifest.json')
const surfaceRoot = path.join(root, 'src', 'product', 'frontend', 'surfaces')
const outputFile = path.join(root, 'src', 'product', 'frontend', 'generated', 'surfaces.js')

function readJson(file) { return JSON.parse(fs.readFileSync(file, 'utf8')) }
function surfaceFilename(route) { return route.replace(/^pages\//, '').replace(/\//g, '__') + '.json' }

const manifest = readJson(manifestFile)
const routes = Object.keys(manifest.router && manifest.router.pages ? manifest.router.pages : {}).sort()
const byId = {}
const byRoute = {}
let compiled = 0

routes.forEach(function (route) {
  const file = path.join(surfaceRoot, surfaceFilename(route))
  if (!fs.existsSync(file)) return
  const surface = readJson(file)
  if (!surface.id || surface.route !== route) throw new Error('Invalid V3 surface identity: ' + file)
  if (byId[surface.id]) throw new Error('Duplicate V3 surface id: ' + surface.id)
  byId[surface.id] = surface
  byRoute[route] = surface.id
  compiled += 1
})

const banner = [
  '// AUTO-GENERATED by scripts/compile-v3-surfaces.js.',
  '// Source authority: src/product/frontend/surfaces/*.json.',
  '// Do not edit this file by hand.',
  ''
].join('\n')
const output = banner +
  'var byId = ' + JSON.stringify(byId, null, 2) + '\n\n' +
  'var byRoute = ' + JSON.stringify(byRoute, null, 2) + '\n\n' +
  'module.exports = { byId: byId, byRoute: byRoute }\n'

fs.mkdirSync(path.dirname(outputFile), { recursive: true })
fs.writeFileSync(outputFile, output, 'utf8')
console.log('Compiled ' + compiled + '/' + routes.length + ' V3 JSON surfaces -> ' + path.relative(root, outputFile))
